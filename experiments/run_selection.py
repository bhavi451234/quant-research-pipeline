"""
Best strategy per stock, chosen WITHOUT hindsight (Phase 11).

Every strategy is run on the tuning period (2014-2019) with its original
default settings. Each stock then gets the strategy with the highest mean
Sharpe there, and the portfolio config is written from those picks. The
evaluation windows never influence the choice, so the resulting portfolio is
a fair out-of-sample estimate, not the hindsight upper bound it used to be.

    python experiments/run_selection.py
    python experiments/run_portfolio.py --config config/portfolio_best_per_ticker.yaml
"""

import sys
from pathlib import Path

import pandas as pd
import yaml

sys.path.append(str(Path(__file__).resolve().parents[1]))

from experiments.run_tuning import TUNE_START, check_no_overlap, load_config, tuning_config
from src.pipeline import run_walkforward, run_walkforward_ml

CANDIDATE_CONFIGS = [
    "config/walkforward_sma.yaml",
    "config/walkforward_ema.yaml",
    "config/walkforward_momentum.yaml",
    "config/walkforward_rsi.yaml",
    "config/walkforward_bollinger.yaml",
    "config/walkforward_ml.yaml",
    "config/walkforward_ml_gb.yaml",
]
PORTFOLIO_BASE = "config/portfolio_single_strategy.yaml"
PORTFOLIO_OUT = "config/portfolio_best_per_ticker.yaml"
FALLBACK = "logistic_regression_walkforward"  # used when a stock has too little tuning data
MIN_TICKER_WINDOWS = 5  # a strategy needs this many valid tuning windows on a stock to be eligible


def score_candidates(configs: dict) -> pd.DataFrame:
    """Mean Sharpe on the tuning period for every (strategy, stock) pair."""
    rows = []
    for name, base in configs.items():
        cfg = tuning_config(base)
        results = run_walkforward_ml(cfg) if "ml" in cfg else run_walkforward(cfg)
        for ticker, res in results.items():
            sharpes = res["per_window"]["sharpe"].dropna()
            rows.append({
                "ticker": ticker,
                "strategy": name,
                "mean_sharpe": sharpes.mean(),
                "n_windows": len(sharpes),
            })
        print(f"done: {name}")
    return pd.DataFrame(rows)


def choose(scores: pd.DataFrame, tickers: list) -> dict:
    """The best eligible strategy per stock, or the fallback if none is eligible."""
    chosen = {}
    for ticker in tickers:
        eligible = scores[(scores["ticker"] == ticker) & (scores["n_windows"] >= MIN_TICKER_WINDOWS)]
        if eligible.empty:
            chosen[ticker] = FALLBACK
        else:
            chosen[ticker] = eligible.loc[eligible["mean_sharpe"].idxmax(), "strategy"]
    return chosen


def strategy_entry(cfg: dict) -> dict:
    """One ticker's entry for portfolio.per_ticker_strategy, built from a walk-forward config."""
    if "ml" in cfg:
        ml = cfg["ml"]
        return {
            "type": "ml",
            "model_type": ml.get("model_type", "logistic"),
            "feature_columns": ml["feature_columns"],
            "threshold": ml.get("threshold", 0.05),
        }
    return {"type": "strategy", "name": cfg["strategy"]["name"], "params": cfg["strategy"]["params"]}


def build_portfolio_config(configs: dict, chosen: dict) -> dict:
    """The single-strategy portfolio config, with per-ticker strategies filled in."""
    out = load_config(PORTFOLIO_BASE)
    out["experiment_name"] = "portfolio_best_per_ticker"

    # All stocks share one feature list, so it must contain every feature any chosen strategy needs.
    features = list(out["features"])
    for name in set(chosen.values()):
        for feature in configs[name]["features"]:
            if feature not in features:
                features.append(feature)
    out["features"] = features

    out["portfolio"]["per_ticker_strategy"] = {
        ticker: strategy_entry(configs[name]) for ticker, name in chosen.items()
    }
    return out


def write_config(cfg: dict, path: str) -> None:
    header = (
        "# Generated by experiments/run_selection.py - do not edit by hand.\n"
        f"# Each stock's strategy was chosen on {TUNE_START} to 2019-12-31 data only,\n"
        "# so the evaluation windows never influenced the choice (no hindsight).\n\n"
    )
    with open(path, "w") as f:
        f.write(header)
        yaml.safe_dump(cfg, f, sort_keys=False)


def main():
    configs = {}
    for path in CANDIDATE_CONFIGS:
        cfg = load_config(path)
        configs[cfg["experiment_name"]] = cfg

    first_test_day = check_no_overlap(configs[FALLBACK])
    print(f"\nSelecting on {TUNE_START} to 2019-12-31; evaluation starts {first_test_day.date()}.\n")

    scores = score_candidates(configs)
    scores.to_csv("results/selection.csv", index=False)

    pd.set_option("display.width", 220)
    print("\n=== Mean Sharpe on the tuning period ===")
    print(scores.pivot(index="strategy", columns="ticker", values="mean_sharpe").round(2).to_string())
    print("\n=== Valid windows behind each number ===")
    print(scores.pivot(index="strategy", columns="ticker", values="n_windows").to_string())

    tickers = list(load_config(PORTFOLIO_BASE)["portfolio"]["allocations"])
    chosen = choose(scores, tickers)
    print(f"\nChosen strategy per stock (needs {MIN_TICKER_WINDOWS}+ valid windows, else {FALLBACK}):")
    for ticker, name in chosen.items():
        print(f"  {ticker}: {name}")

    write_config(build_portfolio_config(configs, chosen), PORTFOLIO_OUT)
    print(f"\nWrote {PORTFOLIO_OUT}")


if __name__ == "__main__":
    main()